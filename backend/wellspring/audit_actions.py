def action_name(code):
    return ACTION_LABELS.get(code, '其他操作')


def action_condition(column, term):
    """Search translated descriptions as well as stable codes, escaping SQL wildcards."""
    term = term.strip()
    matching = [code for code, label in ACTION_LABELS.items() if term.casefold() in label.casefold() or term.casefold() in code.casefold()]
    return or_(column.contains(term, autoescape=True), column.in_(matching))
