import { test, expect, type Page } from '@playwright/test'

async function login(page:Page, user:string) {
  await page.goto('/')
  await page.getByLabel('账号', {exact:true}).fill(user)
  await page.getByLabel('密码', {exact:true}).fill('synthetic-test-password')
  await page.getByRole('button',{name:'登录系统'}).click()
  await page.getByRole('navigation',{name:'主导航'}).waitFor()
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'污水监测',exact:true}).click()
}

test('点位、采样、检测、独立复核与同口径趋势闭环', async ({page}, testInfo) => {
  const stamp=Date.now().toString(), site=`POINT-${stamp}`, sample=`WATER-${stamp}`
  await login(page,'alice')
  await page.getByRole('button',{name:'新增采样点',exact:true}).click()
  await page.getByLabel('点位编号',{exact:true}).fill(site)
  await page.getByLabel('点位名称',{exact:true}).fill('合成污水采样点')
  await page.getByLabel('所属区域',{exact:true}).fill('合成区域')
  await page.getByLabel('污水处理厂',{exact:true}).fill('合成污水处理厂')
  await page.getByRole('button',{name:'保存采样点',exact:true}).click()
  await page.getByRole('row').filter({hasText:site}).getByRole('button',{name:'登记采样',exact:true}).click()
  await page.getByLabel('样本编号',{exact:true}).fill(sample)
  await page.getByLabel('采样时间（北京时间）',{exact:true}).fill('2026-11-10T08:00')
  await page.getByLabel('采样人',{exact:true}).fill('合成采样员')
  await page.getByRole('button',{name:'保存采样记录',exact:true}).click()
  await page.getByRole('row').filter({hasText:sample}).getByRole('button',{name:'录入结果',exact:true}).click()
  await page.getByLabel('检测指标',{exact:true}).fill('合成指标')
  await page.getByLabel('检测浓度（ng/L）',{exact:true}).fill('12.123456')
  await page.getByLabel('定量限（ng/L）',{exact:true}).fill('1')
  await page.getByLabel('检测实验室',{exact:true}).fill('合成实验室')
  await page.getByLabel('检测方法',{exact:true}).fill('合成方法')
  await page.getByLabel('报告编号 / 版本',{exact:true}).fill(`REPORT-${stamp}`)
  await page.getByRole('button',{name:'保存结果草稿',exact:true}).click()
  const row=page.getByRole('row').filter({hasText:sample})
  await expect(row).toContainText('待复核')
  await expect(row.getByRole('button',{name:'复核',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'退出',exact:true}).click()
  await login(page,'receiver')
  await page.getByRole('tab',{name:'检测结果',exact:true}).click()
  await row.getByRole('button',{name:'复核',exact:true}).click()
  await page.getByLabel('复核说明',{exact:true}).fill('已核对合成报告和方法')
  await page.getByRole('button',{name:'确认复核',exact:true}).click()
  await expect(row).toContainText('已复核')
  await page.getByRole('tab',{name:'趋势研判',exact:true}).click()
  await page.getByRole('combobox',{name:'趋势点位',exact:true}).selectOption({label:`${site} · 合成污水采样点`})
  await page.getByLabel('趋势指标',{exact:true}).fill('合成指标')
  await page.getByLabel('趋势实验室',{exact:true}).fill('合成实验室')
  await page.getByLabel('趋势检测方法',{exact:true}).fill('合成方法')
  await page.getByLabel('开始日期',{exact:true}).fill('2026-11-10')
  await page.getByLabel('结束日期',{exact:true}).fill('2026-11-10')
  await page.getByRole('button',{name:'查看趋势',exact:true}).click()
  await expect(page.getByRole('img',{name:'污水检测浓度趋势图，详细数值见下表'})).toBeVisible()
  await expect(page.getByRole('row').filter({hasText:sample})).toContainText('12.123456')
  await page.screenshot({path:testInfo.outputPath('wastewater-trend.png'),fullPage:true})
  await page.getByRole('button',{name:'退出',exact:true}).click()
  await login(page,'outsider')
  await expect(page.getByRole('row').filter({hasText:site})).toHaveCount(0)
})
