import {test,expect,type Page} from '@playwright/test'

async function login(page:Page,user:string,password='synthetic-test-password'){
 await page.goto('/')
 await page.getByLabel('账号',{exact:true}).fill(user);await page.getByLabel('密码',{exact:true}).fill(password)
 await page.getByRole('button',{name:'登录系统'}).click();await page.getByRole('navigation',{name:'主导航'}).waitFor()
}

test('系统管理配置、权限生效、重置密码及导入入口归位',async({page},testInfo)=>{
 const stamp=Date.now().toString(),roleName=`只读案件-${stamp}`,user=`reader-${stamp}`
 await login(page,'superadmin')
 const nav=page.getByRole('navigation',{name:'主导航'})
 for(const name of ['用户管理','角色管理','权限管理','组织管理'])await expect(nav.getByRole('button',{name,exact:true})).toBeVisible()
 await expect(nav.getByRole('button',{name:'数据导入',exact:true})).toHaveCount(0)
 await nav.getByRole('button',{name:'组织管理',exact:true}).click()
 await page.getByRole('button',{name:'新增组织',exact:true}).click()
 await page.getByLabel('组织名称',{exact:true}).fill(`合成组织-${stamp}`)
 await page.getByRole('button',{name:'保存组织',exact:true}).click()
 await expect(page.getByRole('row').filter({hasText:`合成组织-${stamp}`})).toBeVisible()
 await nav.getByRole('button',{name:'角色管理',exact:true}).click()
 await page.getByRole('button',{name:'新增角色',exact:true}).click()
 await page.getByLabel('角色代码',{exact:true}).fill(`reader_${stamp}`)
 await page.getByLabel('角色名称',{exact:true}).fill(roleName)
 await page.getByRole('checkbox',{name:'案件管理查询',exact:true}).check()
 await page.getByRole('checkbox',{name:'查看本人操作记录',exact:true}).check()
 await page.getByRole('button',{name:'保存角色',exact:true}).click()
 await expect(page.getByRole('row').filter({hasText:roleName})).toBeVisible()
 await nav.getByRole('button',{name:'权限管理',exact:true}).click()
 await page.getByRole('combobox',{name:'选择授权角色',exact:true}).selectOption({label:`${roleName}（普通用户）`})
 await expect(page.getByRole('checkbox',{name:'案件管理查询 cases.read',exact:true})).toBeChecked()
 await nav.getByRole('button',{name:'用户管理',exact:true}).click()
 await page.getByRole('button',{name:'新增用户',exact:true}).click()
 await page.getByLabel('账号',{exact:true}).fill(user)
 await page.getByLabel('初始密码',{exact:true}).fill('reader-initial-password')
 await page.getByRole('combobox',{name:'所属组织',exact:true}).selectOption({label:'浏览器回归组织'})
 await page.getByRole('combobox',{name:'分配角色',exact:true}).selectOption({label:roleName})
 await page.getByRole('button',{name:'保存用户',exact:true}).click()
 const row=page.getByRole('row').filter({hasText:user});await expect(row).toBeVisible()
 await page.screenshot({path:testInfo.outputPath('user-management.png'),fullPage:true})
 await row.getByRole('button',{name:'重置密码',exact:true}).click()
 await page.getByLabel('新密码',{exact:true}).fill('reader-reset-password')
 await page.getByRole('button',{name:'确认重置密码',exact:true}).click()
 await expect(page.getByText('密码已重置，旧会话已撤销。请通过受控方式交付新密码。')).toBeVisible()
 await nav.getByRole('button',{name:'案件管理',exact:true}).click()
 await page.getByRole('button',{name:'批量导入 / 导入记录',exact:true}).click()
 await expect(page.getByRole('button',{name:'新建导入批次',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'新建导入批次',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'暂存 CSV',exact:true})).toBeVisible()
 await page.getByRole('dialog',{name:'暂存 CSV',exact:true}).getByRole('button',{name:/^关闭/}).click()
 await page.getByRole('button',{name:'当前账号菜单',exact:true}).click();await page.getByRole('button',{name:'退出',exact:true}).click()
 await login(page,user,'reader-reset-password')
 await expect(nav.getByRole('button',{name:'案件管理',exact:true})).toBeVisible()
 for(const name of ['用户管理','角色管理','权限管理','组织管理','污水监测','接警信息'])await expect(nav.getByRole('button',{name,exact:true})).toHaveCount(0)
 await nav.getByRole('button',{name:'案件管理',exact:true}).click()
 await expect(page.getByRole('heading',{name:'新建案件',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'批量导入 / 导入记录',exact:true})).toHaveCount(0)
 const denied=await page.evaluate(async()=>{const token=sessionStorage.getItem('wellspring.session');const response=await fetch('/api/cases',{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json','Idempotency-Key':'synthetic-denied'},body:JSON.stringify({number:'not-allowed',title:'不应写入'})});return response.status})
 expect(denied).toBe(403)
})
