import { test, expect } from '@playwright/test'
import ExcelJS from 'exceljs'

test('接警新建和关联案件、保留来源快照、撤销及重新关联',async({page})=>{
  const stamp=Date.now().toString(), first=`ALARM-${stamp}-1`,second=`ALARM-${stamp}-2`,number=`CASE-${stamp}`
  await page.goto('/')
  await page.getByLabel('账号',{exact:true}).fill('alice')
  await page.getByLabel('密码',{exact:true}).fill('synthetic-test-password')
  await page.getByRole('button',{name:'登录系统'}).click()
  const nav=page.getByRole('navigation',{name:'主导航'})
  await nav.getByRole('button',{name:'接警信息',exact:true}).click()
  await expect(nav.getByRole('button',{name:'业务案件',exact:true})).toHaveCount(0)
  const workbook=new ExcelJS.Workbook(),sheet=workbook.addWorksheet('接警')
  sheet.addRow(['接警编号','报警内容','备注']);sheet.addRow([first,'合成原始报警内容','原始备注']);sheet.addRow([second,'第二条合成接警','第二备注'])
  await page.locator('input[type=file]').setInputFiles({name:'intakes.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(await workbook.xlsx.writeBuffer())})
  const firstRow=page.getByRole('row').filter({hasText:first}),secondRow=page.getByRole('row').filter({hasText:second})
  await firstRow.getByRole('button',{name:'转办 / 关联',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'接警转办与案件关联'})
  await dialog.getByLabel('案件编号',{exact:true}).fill(number)
  await dialog.getByLabel('案件名称',{exact:true}).fill('合成转办案件')
  await dialog.getByLabel('转办 / 关联依据',{exact:true}).fill('核对合成接警后转办')
  await dialog.getByRole('button',{name:'确认创建并关联',exact:true}).click()
  await expect(dialog.getByText('案件记录已创建，原接警信息和来源快照已保留。')).toBeVisible()
  await expect(dialog.getByRole('button',{name:'确认创建并关联',exact:true})).toHaveCount(0)
  await dialog.getByRole('button',{name:'查看案件',exact:true}).click()
  const caseRow=page.getByRole('row').filter({hasText:number})
  await caseRow.getByRole('button',{name:'接警来源',exact:true}).click()
  const sourceRow=page.getByRole('row').filter({hasText:first})
  await expect(sourceRow).toContainText('新建案件')
  await sourceRow.getByRole('button',{name:'来源快照',exact:true}).click()
  await expect(page.getByText('合成原始报警内容',{exact:true})).toBeVisible()
  await nav.getByRole('button',{name:'接警信息',exact:true}).click()
  await expect(firstRow).toContainText(number)
  await expect(firstRow.getByRole('button',{name:'转办 / 关联',exact:true})).toHaveCount(0)
  await firstRow.getByRole('button',{name:'详情',exact:true}).click()
  const detail=page.getByRole('dialog',{name:'接警信息详情'})
  await detail.getByRole('button',{name:'编辑',exact:true}).click()
  await detail.getByLabel('报警内容',{exact:true}).fill('后续更正内容')
  await detail.getByRole('button',{name:'保存修改',exact:true}).click()
  await expect(detail).not.toBeVisible()
  await secondRow.getByRole('button',{name:'转办 / 关联',exact:true}).click()
  await dialog.getByRole('combobox',{name:'办理方式',exact:true}).selectOption('EXISTING')
  await dialog.getByLabel('查找已有案件',{exact:true}).fill(number)
  await dialog.getByRole('button',{name:'查找案件',exact:true}).click()
  await dialog.getByRole('combobox',{name:'已有案件',exact:true}).selectOption({label:`${number} · 合成转办案件`})
  await dialog.getByLabel('转办 / 关联依据',{exact:true}).fill('第二条来源补充关联')
  await dialog.getByRole('button',{name:'确认关联已有案件',exact:true}).click()
  await expect(dialog.getByText('已关联已有案件，未重复创建案件。')).toBeVisible()
  await dialog.getByRole('button',{name:'查看案件',exact:true}).click()
  await expect(caseRow).toHaveCount(1)
  await caseRow.getByRole('button',{name:'接警来源',exact:true}).click()
  await sourceRow.getByRole('button',{name:'来源快照',exact:true}).click()
  await expect(page.getByText('合成原始报警内容',{exact:true})).toBeVisible()
  await sourceRow.getByRole('button',{name:'撤销关联',exact:true}).click()
  await page.getByLabel('撤销依据',{exact:true}).fill('合成重新核对')
  await page.getByRole('button',{name:'确认撤销关联',exact:true}).click()
  await expect(sourceRow).toContainText('已撤销')
  await nav.getByRole('button',{name:'接警信息',exact:true}).click()
  await expect(firstRow.getByRole('button',{name:'转办 / 关联',exact:true})).toBeVisible()
})
