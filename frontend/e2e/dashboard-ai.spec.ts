import {test,expect} from '@playwright/test'

test('大屏统计、周期、全屏与 AI 模型连接、生成草稿和个人历史',async({page},testInfo)=>{
  await page.setViewportSize({width:1920,height:1080})
  await page.goto('/')
  await page.getByLabel('账号',{exact:true}).fill('superadmin')
  await page.getByLabel('密码',{exact:true}).fill('synthetic-test-password')
  await page.getByRole('button',{name:'登录系统'}).click()
  const nav=page.getByRole('navigation',{name:'主导航'});await nav.waitFor()
  await page.evaluate(async()=>{
    const response=await fetch('/api/cases',{method:'POST',headers:{Authorization:'Bearer '+sessionStorage.getItem('wellspring.session'),'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({number:'DASHBOARD-'+Date.now(),title:'大屏合成案件'})})
    if(!response.ok)throw Error(await response.text())
  })
  await nav.getByRole('button',{name:'数据大屏',exact:true}).click()
  await expect(page.locator('.screen-metric')).toHaveCount(6)
  await expect(page.locator('.screen-metric').filter({hasText:'案件草稿'}).locator('strong')).not.toHaveText('0')
  await page.getByRole('combobox',{name:'新增统计周期',exact:true}).selectOption('7')
  await expect(page.locator('.screen-metric').first()).toContainText('近 7 天新增')
  await page.getByRole('button',{name:'查看每日数据',exact:true}).click()
  await expect(page.locator('.screen-trend tbody tr')).toHaveCount(7)
  await page.getByRole('button',{name:'全屏展示',exact:true}).click()
  await expect(page.locator('.data-screen')).toHaveClass(/is-fullscreen/)
  await page.getByRole('button',{name:'退出全屏',exact:true}).click()
  await page.getByRole('button',{name:'收起每日数据',exact:true}).click()
  await page.screenshot({path:testInfo.outputPath('data-screen.png'),fullPage:true})
  await nav.getByRole('button',{name:'智能研判',exact:true}).click()
  await page.getByRole('button',{name:'配置模型服务',exact:true}).click()
  await expect(page.getByLabel('模型名称',{exact:true})).toHaveValue('synthetic-model')
  await page.getByRole('button',{name:'测试模型连接',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'配置模型服务',exact:true}).locator('.success[role=status]')).toContainText('连接成功')
  await page.getByRole('dialog',{name:'配置模型服务',exact:true}).getByRole('button',{name:'取消',exact:true}).click()
  await nav.getByRole('button',{name:'智能研判',exact:true}).click()
  await expect(page.getByText('服务已启用',{exact:true})).toBeVisible()
  await page.getByLabel('待处理文本',{exact:true}).fill('合成资料：今日在合成点位完成采样，报告需要人工核验。')
  const submit=page.getByRole('button',{name:'生成草稿',exact:true})
  await expect(submit).toBeDisabled()
  await page.getByRole('checkbox',{name:'我已核对内容，确认发送至管理员配置的模型服务。',exact:true}).check()
  await submit.click()
  await expect(page.locator('.ai-result')).toContainText('合成模型草稿')
  await expect(page.locator('.ai-result')).toContainText('<script>不得执行</script>')
  await expect(page.locator('.ai-result script')).toHaveCount(0)
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'下载草稿',exact:true}).click()
  expect((await downloadEvent).suggestedFilename()).toMatch(/AI草稿.*\.txt$/)
  await page.screenshot({path:testInfo.outputPath('ai-draft.png'),fullPage:true})
  await page.getByRole('combobox',{name:'处理方式',exact:true}).selectOption('dashboard')
  await page.getByRole('button',{name:'预览汇总数据',exact:true}).click()
  await expect(page.getByText('查看统计预览',{exact:true})).toBeVisible()
  await page.getByRole('checkbox',{name:'我已核对内容，确认发送至管理员配置的模型服务。',exact:true}).check()
  await submit.click()
  await expect(page.locator('.ai-page tbody tr').filter({hasText:'统计解读'})).toHaveCount(1)
  await expect(page.locator('.ai-page tbody tr').filter({hasText:'统计解读'})).toContainText('已生成草稿')
  await page.setViewportSize({width:768,height:900})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await nav.getByRole('button',{name:'数据大屏',exact:true}).click()
  await expect(page.locator('.screen-metric')).toHaveCount(6)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('data-screen-768.png'),fullPage:true})
  await page.getByRole('button',{name:'退出',exact:true}).click()
  await page.getByLabel('账号',{exact:true}).fill('outsider')
  await page.getByLabel('密码',{exact:true}).fill('synthetic-test-password')
  await page.getByRole('button',{name:'登录系统'}).click()
  await nav.getByRole('button',{name:'智能研判',exact:true}).click()
  await expect(page.getByText('当前角色没有模型生成权限',{exact:true})).toBeVisible()
  await expect(page.locator('.ai-page tbody tr')).toHaveCount(0)
  await expect(nav.getByRole('button',{name:'模型服务',exact:true})).toHaveCount(0)
})
