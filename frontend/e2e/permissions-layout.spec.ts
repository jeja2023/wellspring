import {test,expect} from '@playwright/test'

test('权限表格与管理页布局一致，筛选、分页、未保存更改保护及授权保存可用',async({page},testInfo)=>{
  await page.setViewportSize({width:1920,height:1080})
  await page.goto('/')
  await page.getByLabel('账号',{exact:true}).fill('superadmin')
  await page.getByLabel('密码',{exact:true}).fill('synthetic-test-password')
  await page.getByRole('button',{name:'登录系统'}).click()
  const nav=page.getByRole('navigation',{name:'主导航'})
  await nav.waitFor()
  const role=await page.evaluate(async()=>{
    const response=await fetch('/api/system/roles',{
      method:'POST',headers:{Authorization:'Bearer '+sessionStorage.getItem('wellspring.session'),'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},
      body:JSON.stringify({code:'permission_layout_'+Date.now(),name:'案件协作管理员',kind:'ADMIN',description:'负责案件登记、业务协作与本组织账号维护。',permissions:['cases.read','cases.write','cases.import','audit.read'],active:true}),
    })
    if(!response.ok)throw Error(await response.text())
    return response.json() as Promise<{id:string}>
  })
  await nav.getByRole('button',{name:'权限管理',exact:true}).click()
  await expect(page.getByText('尚未选择授权角色',{exact:true})).toBeVisible()
  const chooser=page.getByRole('combobox',{name:'选择授权角色',exact:true})
  const save=page.getByRole('button',{name:'保存角色权限',exact:true})
  const showSystem=async()=>{await page.getByRole('combobox',{name:'业务模块',exact:true}).selectOption('系统管理');await page.getByRole('button',{name:'查询',exact:true}).click()}
  await expect(save).toBeDisabled()
  await chooser.selectOption(role.id)
  await expect(page.getByRole('definition').filter({hasText:'案件协作管理员'})).toBeVisible()
  await expect(save).toBeDisabled()
  await showSystem()
  await expect(page.getByRole('checkbox',{name:'配置角色（超级管理员） system.roles',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'重置',exact:true}).click()
  await page.screenshot({path:testInfo.outputPath('permissions-desktop.png'),fullPage:true})

  const search=page.getByRole('searchbox',{name:'搜索权限',exact:true})
  await search.fill('intake.write')
  await page.getByRole('button',{name:'查询',exact:true}).click()
  await expect(page.locator('.permission-option')).toHaveCount(1)
  await expect(page.getByRole('checkbox',{name:'接警信息办理与修改 intake.write',exact:true})).toBeVisible()
  await search.fill('不存在的权限')
  await page.getByRole('button',{name:'查询',exact:true}).click()
  await expect(page.getByRole('cell').filter({hasText:'没有符合条件的权限'})).toBeVisible()
  await page.getByRole('button',{name:'显示全部权限',exact:true}).click()
  await page.getByRole('checkbox',{name:'仅看已选',exact:true}).check()
  await expect(page.locator('.permission-option')).toHaveCount(4)
  await page.getByRole('button',{name:'重置',exact:true}).click()
  await page.getByRole('combobox',{name:'业务模块',exact:true}).selectOption('案件管理')
  await page.getByRole('button',{name:'查询',exact:true}).click()
  await expect(page.locator('.permission-option')).toHaveCount(3)
  const read=page.getByRole('checkbox',{name:'案件管理查询 cases.read',exact:true})
  await read.uncheck()
  await expect(page.getByText('还需勾选：案件管理查询',{exact:true})).toBeVisible()
  await expect(save).toBeDisabled()
  await page.getByRole('button',{name:'撤销更改',exact:true}).click()
  await expect(read).toBeChecked()
  await page.getByRole('button',{name:'重置',exact:true}).click()

  const manageUsers=page.getByRole('checkbox',{name:'管理本组织普通账号 system.users',exact:true})
  await showSystem()
  await manageUsers.check()
  await expect(page.getByText('1 项权限更改待保存',{exact:true})).toBeVisible()
  await chooser.selectOption('wellspring-business-user')
  await expect(page.getByRole('button',{name:'继续编辑',exact:true})).toBeVisible()
  await expect(chooser).toHaveValue(role.id)
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  await expect(manageUsers).toBeChecked()
  await chooser.selectOption('wellspring-business-user')
  await page.getByRole('button',{name:'放弃并切换',exact:true}).click()
  await expect(chooser).toHaveValue('wellspring-business-user')
  await showSystem()
  await expect(manageUsers).toBeDisabled()
  await expect(save).toBeDisabled()
  await chooser.selectOption(role.id)
  await showSystem()
  await manageUsers.check()
  await save.click()
  await expect(page.getByText('已保存；账号或角色授权变化后，受影响账号的旧会话已撤销。',{exact:true})).toBeVisible()
  await expect(save).toBeDisabled()
  await nav.getByRole('button',{name:'用户管理',exact:true}).click()
  const standardCard=await page.locator('.page-list>.card').first().evaluate(element=>{
    const style=getComputedStyle(element)
    return {padding:style.padding,borderRadius:style.borderRadius,borderColor:style.borderColor,background:style.backgroundColor}
  })
  await nav.getByRole('button',{name:'权限管理',exact:true}).click()
  await page.getByRole('combobox',{name:'选择授权角色',exact:true}).selectOption(role.id)
  await showSystem()
  await expect(manageUsers).toBeChecked()
  await page.getByRole('button',{name:'重置',exact:true}).click()
  const table=page.getByRole('table',{name:'权限目录',exact:true})
  await expect(table.getByRole('columnheader')).toHaveText(['序号','业务模块','权限名称','权限代码','配置范围','授权状态'])
  const pagination=page.getByRole('navigation',{name:'数据分页',exact:true})
  await pagination.getByRole('button',{name:'末页',exact:true}).click()
  const lastPage=Number(await pagination.locator('[aria-current=page]').textContent())
  expect(lastPage).toBeGreaterThan(1)
  await expect(table.locator('tbody tr').first().locator('td').first()).toHaveText(String((lastPage-1)*20+1))
  await pagination.getByRole('button',{name:'首页',exact:true}).click()
  await expect(table.locator('tbody tr').first().locator('td').first()).toHaveText('1')
  for(const width of [1440,768]){
    await page.setViewportSize({width,height:1024})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    expect(await page.locator('.permission-workspace').evaluate(element=>{
      const style=getComputedStyle(element)
      return {padding:style.padding,borderRadius:style.borderRadius,borderColor:style.borderColor,background:style.backgroundColor}
    })).toEqual(standardCard)
    expect(await page.locator('.permission-save-bar').evaluate(element=>getComputedStyle(element).position)).toBe('static')
    await expect(page.locator('.permission-workspace .card')).toHaveCount(0)
    const filterBounds=await page.locator('.permission-filters').boundingBox()
    const tableBounds=await table.boundingBox()
    expect(tableBounds!.y).toBeGreaterThan(filterBounds!.y+filterBounds!.height)
    await save.scrollIntoViewIfNeeded()
    await expect(save).toBeVisible()
    await page.screenshot({path:testInfo.outputPath('permissions-'+width+'.png'),fullPage:true})
  }
})
