import { test, expect } from '@playwright/test'

test('新建表单统一弹窗、单一顶部关闭与焦点恢复、失败保留及成功关闭', async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 1920, height: 1080 })
    await page.goto('/')
    await page.getByLabel('账号', { exact: true }).fill('superadmin')
    await page.getByLabel('密码', { exact: true }).fill('synthetic-test-password')
    await page.getByRole('button', { name: '登录系统' }).click()
    const nav = page.getByRole('navigation', { name: '主导航' })
    for (const [name, button, title] of [['案件管理', '新建案件', '新建案件'], ['人员档案', '新建人员', '新建人员档案'], ['情报线索', '新建线索', '新建线索'], ['用户管理', '新增用户', '新增用户'], ['角色管理', '新增角色', '新增角色'], ['组织管理', '新增组织', '新增组织']]) {
        await nav.getByRole('button', { name, exact: true }).click()
        await expect(page.locator('.form-dialog')).toHaveCount(0)
        await expect(page.locator('.two-column')).toHaveCount(0)
        const trigger = page.getByRole('button', { name: button, exact: true })
        await expect(trigger).toBeEnabled(); await trigger.click()
        const dialog = page.getByRole('dialog', { name: title, exact: true })
        await expect(dialog).toBeVisible()
        const bounds = await dialog.boundingBox()
        expect(bounds!.x).toBeGreaterThan(0); expect(bounds!.width).toBeLessThan(1000)
        await expect(dialog.getByRole('button', { name: /^关闭/ })).toHaveCount(1)
        await expect(dialog.getByRole('button', { name: '取消', exact: true })).toHaveCount(0)
        await dialog.getByRole('button', { name: /^关闭/ }).click()
        await expect(dialog).toHaveCount(0); await expect(trigger).toBeFocused()
    }
    await page.getByRole('button', { name: '当前账号菜单', exact: true }).click()
    await page.getByRole('button', { name: '修改密码', exact: true }).click()
    const password = page.getByRole('dialog', { name: '修改密码', exact: true })
    await expect(password.getByRole('button', { name: '关闭修改密码', exact: true })).toHaveCount(1)
    await expect(password.getByRole('button', { name: '取消', exact: true })).toHaveCount(0)
    await password.getByRole('button', { name: '关闭修改密码', exact: true }).click()
    await nav.getByRole('button', { name: '人员档案', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath('persons-list.png'), fullPage: true })
    const trigger = page.getByRole('button', { name: '新建人员', exact: true }); await trigger.click()
    const dialog = page.getByRole('dialog', { name: '新建人员档案', exact: true })
    await dialog.getByLabel('名称', { exact: true }).fill('合成人员弹窗-' + Date.now())
    await dialog.getByLabel('来源', { exact: true }).fill('合成来源')
    await page.screenshot({ path: testInfo.outputPath('persons-create-dialog.png'), fullPage: true })
    let release: () => void = () => { }
    const pending = new Promise<void>(resolve => { release = resolve })
    let attempts = 0
    await page.route('**/api/person-drafts', async route => {
        if (route.request().method() !== 'POST') return route.continue()
        if (attempts++ === 0) { await pending; return route.fulfill({ status: 422, json: { code: 'VALIDATION_ERROR', message: '合成失败请重试', request_id: 'synthetic-dialog-failure' } }) }
        await route.continue()
    })
    await dialog.getByRole('button', { name: '保存档案', exact: true }).click()
    await expect(dialog.getByRole('button', { name: /^关闭/ })).toBeDisabled()
    await page.keyboard.press('Escape'); await expect(dialog).toBeVisible()
    release()
    await expect(dialog.getByRole('alert')).toContainText('合成失败请重试')
    await expect(dialog.getByLabel('来源', { exact: true })).toHaveValue('合成来源')
    await dialog.getByRole('button', { name: '保存档案', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('row').filter({ hasText: '合成人员弹窗-' })).toHaveCount(1)
    await page.setViewportSize({ width: 768, height: 900 })
    await trigger.click(); const small = await dialog.boundingBox()
    expect(small!.x).toBeGreaterThanOrEqual(15); expect(small!.x + small!.width).toBeLessThanOrEqual(753)
    await dialog.getByRole('button', { name: /^关闭/ }).click()
    await page.setViewportSize({ width: 1440, height: 1080 })
    await nav.getByRole('button', { name: '案件管理', exact: true }).click()
    await page.getByRole('button', { name: '批量导入 / 导入记录', exact: true }).click()
    await page.getByRole('button', { name: '新建导入批次', exact: true }).click()
    const batch = page.getByRole('dialog', { name: '暂存 CSV', exact: true }), number = 'MODAL-CSV-' + Date.now()
    await batch.getByLabel('来源', { exact: true }).fill('弹窗合成导入')
    await batch.getByLabel('文件', { exact: true }).setInputFiles({ name: 'synthetic.csv', mimeType: 'text/csv', buffer: Buffer.from(`案件编号,案件名称\n${number},弹窗CSV案件\n`, 'utf-8') })
    await batch.getByRole('button', { name: '暂存并核对', exact: true }).click()
    await expect(batch).toHaveCount(0)
    await page.getByRole('button', { name: '确认创建符合条件的案件', exact: true }).click()
    await expect(page.getByText('批次已处理；请核对逐行结果', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '案件列表', exact: true }).click()
    await expect(page.getByRole('row').filter({ hasText: number })).toHaveCount(1)
})
