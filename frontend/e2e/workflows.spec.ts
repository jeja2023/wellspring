test('Excel 导入、字段修改、筛选与导出保留前导零', async ({ page }) => {
  const number = `0000-${Date.now()}`
  const workbook = new ExcelJS.Workbook()
  const sheet = workbook.addWorksheet('合成数据')
  sheet.addRow(['接警编号', '接警类型', '报警电话', '备注'])
  sheet.addRow([number, '浏览器测试类型', '0123456', '合成备注'])
  const bytes = Buffer.from(await workbook.xlsx.writeBuffer())
  await login(page)
  await page.getByRole('button', { name: '接警信息', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'synthetic.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: bytes })
  const row = page.getByRole('row').filter({ hasText: number })
  await expect(row).toBeVisible({ timeout: 20000 })
  await row.getByRole('button', { name: '详情', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '接警信息详情' })
  await expect(dialog).toContainText('0123456')
  await dialog.getByRole('button', { name: '编辑', exact: true }).click()
  await dialog.getByLabel('备注', { exact: true }).fill('合成修改后的备注')
  await dialog.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByLabel('关键词', { exact: true }).fill(number)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toBeVisible()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出当前结果', exact: true }).click()
  const download = await downloaded
  const path = await download.path()
  const exported = new ExcelJS.Workbook()
  await exported.xlsx.readFile(path!)
  expect(exported.worksheets[0].getCell('A2').value).toBe(number)
  expect(exported.worksheets[0].getCell('I2').value).toBe('0123456')
  expect(exported.worksheets[0].getCell('T2').value).toBe('合成修改后的备注')
})

test('接警列表翻页保持统计且不重复请求聚合', async ({ page }) => {
  const prefix = `PAGE-${Date.now()}`
  const workbook = new ExcelJS.Workbook()
  const sheet = workbook.addWorksheet('合成分页')
  sheet.addRow(['接警编号', '接警类型'])
  for (let index = 0; index < 21; index++) sheet.addRow([`${prefix}-${index}`, '分页合成类型'])
  await login(page)
  await page.getByRole('button', { name: '接警信息', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'pages.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(await workbook.xlsx.writeBuffer()) })
  await expect(page.getByText('已导入 21 条记录', { exact: false })).toBeVisible({ timeout: 20000 })
  await page.getByLabel('关键词', { exact: true }).fill(prefix)
  const filtered = page.waitForResponse(response => response.url().endsWith('/case-information/search') && response.request().postDataJSON().keyword === prefix)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await filtered
  await expect(page.getByText('第 1 页 · 共 21 条', { exact: true })).toBeVisible()
  const next = page.waitForResponse(response => response.url().endsWith('/case-information/search') && response.request().postDataJSON().page === 2)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  const response = await next
  expect(response.request().postDataJSON().include_summary).toBe(false)
  expect((await response.json()).statistics).toBeUndefined()
  await expect(page.getByText('第 2 页 · 共 21 条', { exact: true })).toBeVisible()
  await expect(page.locator('.case-information-table tbody tr')).toHaveCount(1)
  await expect(page.locator('.case-information-table tbody tr td').first()).toHaveText('21')
  const pagination=page.getByRole('navigation',{name:'数据分页'})
  const rightAligned=await pagination.evaluate(element=>{
    const bounds=element.getBoundingClientRect(),last=element.lastElementChild!.getBoundingClientRect()
    return {gap:Math.abs(bounds.right-last.right),alignment:getComputedStyle(element).justifyContent,last:element.lastElementChild!.tagName}
  })
  expect(['flex-end','end','flow-end']).toContain(rightAligned.alignment)
  expect(rightAligned.gap,JSON.stringify(rightAligned)).toBeLessThan(2)
  await pagination.getByRole('button',{name:'首页',exact:true}).click()
  await expect(page.locator('.case-information-table tbody tr td').first()).toHaveText('1')
  await expect(page.locator('.case-stat-total')).toContainText('21')
})
