import {test,expect} from '@playwright/test'

test('API Key 输入、模型 ID 获取、未保存连接测试及密钥保留清除',async({page},testInfo)=>{
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('/')
  await page.getByLabel('账号',{exact:true}).fill('superadmin')
  await page.getByLabel('密码',{exact:true}).fill('synthetic-test-password')
  await page.getByRole('button',{name:'登录系统'}).click()
  const nav=page.getByRole('navigation',{name:'主导航'});await nav.waitFor()
  await nav.getByRole('button',{name:'智能研判',exact:true}).click()
  await page.getByRole('button',{name:'配置模型服务',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'配置模型服务',exact:true})
  await expect(nav.getByRole('button',{name:'模型服务',exact:true})).toHaveCount(0)
  const key=page.getByLabel('API Key',{exact:true}),model=page.getByLabel('模型名称',{exact:true})
  await expect(key).toHaveAttribute('type','password')
  await key.fill('synthetic-browser-key')
  await model.fill('')
  await page.getByRole('button',{name:'获取模型列表',exact:true}).click()
  await expect(dialog.locator('.success[role=status]')).toContainText('已获取 2 个模型')
  await page.getByRole('combobox',{name:'可用模型 ID',exact:true}).selectOption('synthetic-model')
  await expect(model).toHaveValue('synthetic-model')
  await page.getByRole('button',{name:'测试模型连接',exact:true}).click()
  await expect(dialog.locator('.success[role=status]')).toContainText('连接成功')
  await expect(key).toHaveValue('synthetic-browser-key')
  await page.getByRole('button',{name:'保存配置',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('已保存')
  await page.getByRole('button',{name:'配置模型服务',exact:true}).click()
  await expect(key).toHaveValue('')
  await expect(page.getByText('已配置（不回显）',{exact:true})).toBeVisible()
  await dialog.getByRole('button',{name:'取消',exact:true}).click()
  await nav.getByRole('button',{name:'工作台',exact:true}).click()
  await nav.getByRole('button',{name:'智能研判',exact:true}).click()
  await page.getByRole('button',{name:'配置模型服务',exact:true}).click()
  await expect(page.getByLabel('API Key',{exact:true})).toHaveValue('')
  await expect(page.getByText('已配置（不回显）',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'获取模型列表',exact:true}).click()
  await expect(dialog.locator('.success[role=status]')).toContainText('已获取 2 个模型')
  await page.screenshot({path:testInfo.outputPath('model-settings-key-and-discovery.png'),fullPage:true})
  await page.getByRole('button',{name:'获取模型列表',exact:true}).click()
  await expect(dialog.locator('.success[role=status]')).toContainText('已获取 2 个模型')
  await key.fill('synthetic-bad-key')
  await page.getByRole('button',{name:'获取模型列表',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('鉴权失败')
  await page.getByRole('button',{name:'清除密钥',exact:true}).click()
  await page.getByRole('button',{name:'保存配置',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button',{name:'配置模型服务',exact:true}).click()
  await expect(dialog.getByText('未配置密钥',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'测试模型连接',exact:true}).click()
  await expect(dialog.locator('.success[role=status]')).toContainText('连接成功')
  await page.setViewportSize({width:768,height:1000})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
