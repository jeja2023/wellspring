"""解析固定依赖，并用 PyPI 发布元数据生成所有平台制品的 SHA-256 锁。"""
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parents[1]


def release_hashes(package):
    name, version = package["metadata"]["name"], package["metadata"]["version"]
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
        release = json.load(response)
    hashes = sorted({item["digests"]["sha256"] for item in release["urls"] if not item["yanked"]})
    if not hashes:
        raise ValueError(f"缺少未撤回的发布制品: {name}=={version}")
    return name.lower().replace("_", "-"), version, hashes


def main():
    for name in ("requirements", "requirements-dev"):
        with tempfile.TemporaryDirectory(prefix="wellspring-lock-") as folder:
            report = Path(folder) / "resolution.json"
            subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
                            "--quiet", "--report", str(report), "-r", str(ROOT / "backend" / f"{name}.txt")],
                           check=True, timeout=300)
            packages = json.loads(report.read_text(encoding="utf-8"))["install"]
        with ThreadPoolExecutor(max_workers=8) as executor:
            resolved = sorted(executor.map(release_hashes, packages))
        lines = ["# Generated by scripts/lock_python_dependencies.py on Python 3.12.\n",
                 "# Includes SHA-256 of every non-yanked release artifact for cross-platform installs.\n",
                 "# Install with: python -m pip install --require-hashes -r " + name + ".lock\n\n"]
        for package, version, hashes in resolved:
            lines.append(f"{package}=={version} \\\n")
            lines.extend("    --hash=sha256:" + digest + (" \\\n" if index < len(hashes) - 1 else "\n")
                         for index, digest in enumerate(hashes))
        destination = ROOT / "backend" / f"{name}.lock"
        destination.write_text("".join(lines), encoding="utf-8", newline="\n")
        print(f"{destination.name}: {len(resolved)} packages", flush=True)


if __name__ == "__main__":
    main()
